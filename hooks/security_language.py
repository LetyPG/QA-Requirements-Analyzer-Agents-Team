#!/usr/bin/env python3
"""
PreToolUse Hook Implementation

Deterministic validation layer that executes BEFORE any tool is used by the
orchestrator agent. This moves critical governance out of the LLM's
probabilistic reasoning and into auditable, predictable Python code.

Responsibilities:
    1. Security Gate  — Block executable / risky file extensions and MIME types
                        using a default-deny policy (fail-closed).
    2. Language Detector — Detect the user's language offline via lingua
                           and inject a structured language rule.
    3. Emit HookResult — Print structured JSON to stdout for the orchestrator.
"""

