# Language Detection
# ===========================================================================

def _detect_language(text: str) -> tuple[str, float]:
    """
    Detect the language of the input text using lingua (offline).

    Returns:
        (language_name, confidence) — e.g. ("Spanish", 0.98)
        Falls back to ("English", raw_confidence) if:
          - lingua is not installed
          - detected language is not in the supported set
          - confidence is below CONFIDENCE_THRESHOLD (0.75)
    """
    if not _LINGUA_AVAILABLE or not text or not text.strip():
        return ("English", 0.0)

    try:
        target_languages = [
            Language.ENGLISH,
            Language.SPANISH,
            Language.PORTUGUESE,
            Language.FRENCH,
            Language.GERMAN,
            Language.ITALIAN,
        ]
        detector = (
            LanguageDetectorBuilder
            .from_languages(*target_languages)
            .with_minimum_relative_distance(0.1)
            .build()
        )
        result = detector.detect_language_of(text)

        if result is None:
            return ("English", 0.0)

        lang_name = _LINGUA_LANGUAGE_MAP.get(result.name, None)
        if lang_name is None:
            return ("English", 0.0)

        # Get confidence score
        confidence_values = detector.compute_language_confidence_values(text)
        confidence = 0.0
        for cv in confidence_values:
            if cv.language == result:
                confidence = round(cv.value, 4)
                break

        if confidence < CONFIDENCE_THRESHOLD:
            # Fallback to English — keep raw score for diagnostics
            return ("English", confidence)

        return (lang_name, confidence)

    except (RuntimeError, LookupError) as e:
        # Log detection failure and fall back to English
        print(f"[WARNING] Language detection failed: {e}", file=sys.stderr)
        return ("English", 0.0)


def build_language_result(
    context: HookContext,
    trace_id: str,
) -> HookResult:
    """
    Run language detection and build an allow HookResult with enriched context.
    """
    detected_lang, confidence = _detect_language(context.user_prompt)
    rule = LANGUAGE_RULES.get(detected_lang, LANGUAGE_RULES["English"])

    sanitized = {
        "user_prompt": context.user_prompt,
        "input_files": context.input_files,
    }

    return HookResult(
        execute_workflow=True,
        trace_id=trace_id,
        language=detected_lang,
        confidence=confidence,
        language_rule=rule,
        sanitized_context=sanitized,
    )


# ===========================================================================
# Utility
# ===========================================================================

def _generate_trace_id() -> str:
    """Generate a UUID4 trace ID for audit trail linkage."""
    return str(uuid.uuid4())


def _parse_stdin() -> tuple[dict, list[str]]:
    """
    Read and parse the JSON payload from stdin (Claude PreToolUse protocol).

    The runtime passes a JSON object with at minimum:
        { "tool_name": "...", "tool_input": { ... } }

    Returns:
        (raw_payload, list_of_file_paths)
    """
    try:
        raw = sys.stdin.read()
        if not raw.strip():
            return ({}, [])
        payload = json.loads(raw)
        tool_input = payload.get("tool_input", {})
        file_paths = _resolve_file_paths(tool_input)
        return (payload, file_paths)
    except json.JSONDecodeError:
        return ({}, [])


def _extract_user_prompt(payload: dict) -> str:
    """
    Extract the user-facing text for language detection.

    Prefers the 'prompt' or 'query' keys in tool_input; falls back to
    searching for any string value longer than 20 chars.
    """
    tool_input = payload.get("tool_input", {})
    for key in ("prompt", "query", "content", "text", "user_prompt"):
        val = tool_input.get(key, "")
        if isinstance(val, str) and len(val.strip()) > 10:
            return val.strip()

    # Fallback: use the longest string value in tool_input
    candidates = [
        v for v in tool_input.values()
        if isinstance(v, str) and len(v.strip()) > 20
    ]
    if candidates:
        return max(candidates, key=len)

    return ""


# ===========================================================================
# Main entrypoint
# ===========================================================================

def main() -> None:
    """
    PreToolUse hook entrypoint.

    Reads tool input from stdin, runs security gate and language detection,
    and emits a HookResult as JSON to stdout.

    Exit code is always 0 — a non-zero exit would crash the agent runtime.
    """
    payload, input_files = _parse_stdin()
    user_prompt = _extract_user_prompt(payload)

    context = HookContext(
        user_prompt=user_prompt,
        input_files=input_files,
    )

    trace_id = _generate_trace_id()

    # --- Phase 1: Security Gate (fail-closed) ---
    block_result = run_security_gate(context)
    if block_result is not None:
        # Ensure the same trace_id is used for consistent audit linkage
        block_result.trace_id = trace_id
        print(json.dumps(block_result.to_dict(), ensure_ascii=False))
        sys.exit(0)

    # --- Phase 1.5: Prompt Injection Gate (fail-closed) ---
    prompt_reason, extracted = _check_prompt_injection(user_prompt)
    if prompt_reason:
        prompt_block = HookResult(
            execute_workflow=False,
            trace_id=trace_id,
            risk_level="high",
            block_reason=prompt_reason,
        )
        print(json.dumps(prompt_block.to_dict(), ensure_ascii=False))
        sys.exit(0)

    # Inject sanitized prompt back into context for language detection
    if extracted and "sanitized_prompt" in extracted:
        context.user_prompt = extracted["sanitized_prompt"]

    # --- Phase 2: Language Detection (enrichment) ---
    allow_result = build_language_result(context, trace_id)
    print(json.dumps(allow_result.to_dict(), ensure_ascii=False))
    sys.exit(0)


if __name__ == "__main__":
    main()