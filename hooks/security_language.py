# ---------------------------------------------------------------------------
# Security constants
# Policy decision: default-deny. Unknown extensions are BLOCKED, not allowed.
# Override: pass allowed_extensions via HookContext.extensions at runtime.
# See README.md §Hook Layer for the rationale behind each category.
# ---------------------------------------------------------------------------

BLOCKED_EXTENSIONS: frozenset[str] = frozenset({
    # Executables & system binaries
    ".exe", ".dll", ".so", ".bat", ".cmd", ".ps1", ".sh",
    # Scripts (including .py — blocked by default; override via extensions)
    ".js", ".vbs", ".py",
    # Binary / packaged
    ".bin", ".apk", ".jar",
    # Office macros
    ".docm", ".xlsm",
})

# Blocked MIME type prefixes / exact values
BLOCKED_MIME_PREFIXES: tuple[str, ...] = (
    "application/x-executable",
    "application/x-sharedlib",
    "application/x-dosexec",
    "application/x-msdownload",
    "application/x-sh",
    "application/x-python",
    "application/java-archive",
    "application/vnd.ms-office",
    "application/zip",          # Catch archive recursion attempts
    "application/x-zip",
)

# File size limit — default 10 MB.
# Decision rationale: resource consumption optimization. Oversized files
# Override: see docs/architecture_implementation_details_roadmap.md Hook Layer for instructions on changing this value.
MAX_FILE_SIZE_MB: int = 10
MAX_FILE_SIZE_BYTES: int = MAX_FILE_SIZE_MB * 1024 * 1024

# ---------------------------------------------------------------------------
# Language detection constants
# Confidence threshold: 0.75.
# Below this value the hook falls back to English and logs the raw score.
# ---------------------------------------------------------------------------

CONFIDENCE_THRESHOLD: float = 0.75

